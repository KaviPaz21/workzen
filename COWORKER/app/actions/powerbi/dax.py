STRING_PATTERN = re.compile(r'"(?:[^"]|"")*"')
BLOCK_COMMENT_PATTERN = re.compile(r"/\*.*?\*/", re.DOTALL)
LINE_COMMENT_PATTERN = re.compile(r"(//|--)[^\n]*")
REFERENCE_PATTERN = re.compile(r"(?:'((?:[^']|'')+)'|\b([A-Za-z_][A-Za-z0-9_]*))?\[([^\]\n]+)\]")
FUNCTION_PATTERN = re.compile(r"(?<![A-Za-z0-9_.\]'])([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)*)\s*\(")
TEXT_AGGREGATES = ("SUM", "AVERAGE")


def strip_dax(text: str) -> str:
    cleaned = STRING_PATTERN.sub(lambda match: '"' + " " * (len(match.group(0)) - 2) + '"', text)
    cleaned = BLOCK_COMMENT_PATTERN.sub(" ", cleaned)
    return LINE_COMMENT_PATTERN.sub(" ", cleaned)


def balanced(text: str) -> bool:
    depth = 0
    for character in re.sub(r"'(?:[^']|'')*'", "", text):
        if character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
            if depth < 0:
                return False
    return depth == 0


def references(text: str) -> list[tuple[str | None, str]]:
    found = []
    for match in REFERENCE_PATTERN.finditer(text):
        table = match.group(1).replace("''", "'") if match.group(1) else match.group(2)
        found.append((table, match.group(3)))
    return found


def function_names(text: str) -> set[str]:
    return {name.upper() for name in FUNCTION_PATTERN.findall(text)}